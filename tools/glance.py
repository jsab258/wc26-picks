def main():
    ap = argparse.ArgumentParser(description="the glance page, phone-first")
    ap.add_argument("--root", default=str(ROOT), help="tree to read")
    ap.add_argument("--out", default=None, help="where to write the page")
    ap.add_argument("--now", default=None, help="ISO clock, for the 24h rule")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    now = parse_now(args.now) if args.now else datetime.datetime.now(
        datetime.timezone.utc)
    root = Path(args.root).resolve()
    out = Path(args.out) if args.out else root / OUT_NAME
    page, model = build(root, now)
    out.write_text(page, encoding="utf-8")
    checks = run_checks(page)
    bad = [n for n, c, _ in checks if not c]
    print("glance: wrote %s, colour=%s %s"
          % (out, model["colour"], " ".join(s for _, _, s in checks)))
    print("glance: %s" % model["why"])
    for name, look in zip(("state", "needsYou", "next", "image", "budget"),
                          model["looks"]):
        print("  %-9s %s | %s" % (name, "read" if look.ok else "NOTHING MEASURED",
                                  look.source))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
