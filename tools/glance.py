def esc(s):
    return html.escape(str(s), quote=True)


def missing_p(look):
    """The one string a missing reading is allowed to render.

    It still NAMES THE PLACE IT LOOKED, because "nothing measured" without a
    path is the same dead end as a zero: a reader cannot tell a source that is
    empty from a source this tool never opened.
    """
    return ('<p class="missing">nothing measured</p>\n'
            '<p class="src">from %s. %s</p>' % (esc(look.source), esc(look.note)))


def source_line(look):
    return '<p class="src">from %s</p>' % esc(look.source)


def why_details(text):
    """The derivation is one tap down even inside a block: constitution law 12
    puts the evidence behind the sentence for Jafar and beside it for agents,
    and a <details> is both without a second page."""
    return ('<details><summary>how this number was read</summary>'
            '<p class="why">%s</p></details>' % esc(text))


def block(n, label, body, extra=""):
    return ('<section class="block%s" data-block="%d">\n<p class="label">%s</p>\n'
            '%s\n</section>' % (extra, n, esc(label), body))


def render_state(look, colour, why):
    if not look.ok:
        body = ('<p class="word">%s</p>\n%s' % (esc(colour), missing_p(look)))
    else:
        body = ('<p class="word">%s</p>\n<p class="say">%s</p>\n'
                '<p class="src">%s, %s hours old, from %s</p>\n%s'
                % (esc(colour), esc(look.get("sentence")), esc(look.get("date")),
                   esc("%.0f" % look.get("age_h")), esc(look.source),
                   why_details(look.note)))
    body += '\n<p class="why">%s</p>' % esc(why)
    return ('<section class="block state" data-block="1" '
            'style="border-left-color: %s">\n<p class="label">%s</p>\n%s\n</section>'
            % (BAR[colour], esc("state"), body))


def render_needs(look):
    if not look.ok:
        return block(2, "needs you", missing_p(look))
    n = look.get("count")
    top = look.get("top")
    if n == 0:
        body = ('<p class="huge">0</p>\n<p class="big">nothing is waiting on '
                'you</p>\n<p class="src">of %d card(s) in %s</p>\n%s'
                % (look.get("examined"), esc(DECISIONS), why_details(look.note)))
    else:
        cls = look.get("top_class") or "UNCLASSIFIED"
        body = ('<p class="huge">%d</p>\n<p class="big">%s</p>\n'
                '<p class="src">top item, %s, of %d card(s) in %s</p>\n%s'
                % (n, esc(top), esc(cls), look.get("examined"), esc(DECISIONS),
                   why_details(look.note)))
    return block(2, "needs you", body)


def render_next(look):
    if not look.ok:
        return block(3, "next visible thing", missing_p(look))
    when = look.get("when") or "unknown"
    body = ('<p class="big">%s</p>\n<p class="say">when: %s</p>\n%s\n%s'
            % (esc(look.get("what")), esc(when), source_line(look),
               why_details(look.note)))
    return block(3, "next visible thing", body)


def render_image(look):
    if not look.ok:
        return block(4, "latest image", missing_p(look))
    body = ('<img class="frame" alt="the latest frame this studio rendered, %s" '
            'src="data:%s;base64,%s">\n<p class="src">%s, %d bytes embedded</p>'
            '\n%s' % (esc(look.source), look.get("mime"), look.get("b64"),
                      esc(look.source), look.get("bytes"),
                      why_details(look.note)))
    return block(4, "latest image", body)


def render_meter(name, value, ceiling, governs):
    """One meter bar. A meter that was not read draws NO bar: an empty track
    reads as zero at a glance, and zero is the one thing an unread meter is
    not."""
    mark = ' <span class="govern">governs</span>' if governs else ""
    if value is None:
        return ('<div class="meter"><div class="top"><span>%s</span>'
                '<span>not read</span></div></div>' % esc(name))
    left = ceiling - value
    return ('<div class="meter"><div class="top"><span>%s%s</span>'
            '<span>%d%% used, %d to the %d%% ceiling</span></div>'
            '<div class="track"><div class="fill" style="width: %d%%; '
            'background: %s"></div><div class="tick" style="left: %d%%"></div>'
            '</div></div>'
            % (esc(name), mark, value, left, ceiling, min(value, 100),
               BAR["RED"] if value >= ceiling else BAR["GREEN"], min(ceiling, 100)))


def render_budget(look):
    if not look.ok:
        return block(5, "budget", missing_p(look))
    ceiling = look.get("ceiling")
    hours = look.get("hours")
    body = (render_meter("total", look.get("total"), ceiling,
                         look.get("govern") == "total")
            + "\n" + render_meter("fable", look.get("fable"), ceiling,
                                  look.get("govern") == "fable")
            + '\n<p class="src">read %s. Hours to reset: %s</p>\n%s'
            % (esc(look.get("when")),
               esc("%.0f" % hours) if hours is not None else "unknown",
               why_details(look.note)))
    return block(5, "budget", body)


