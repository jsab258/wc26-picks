def build(root, now, image_budget=None):
    """The whole page, and the model behind it, from repo state.

    THE ORDER HERE IS THE BYTE ARITHMETIC, and it stopped being a guess on
    2026-09-09. The image used to take whatever the 250 000 byte cap left after
    a flat 4000 byte allowance for the five blocks, which was true while block 2
    was a count and one headline. Block 2 now carries every waiting card's full
    text, so the allowance is MEASURED rather than allowed for, in three numbers
    that each print on the done line:

      imageFloorBytes   the fewest bytes this frame can be shown in at all,
                        measured by asking the encoder for a budget nothing
                        fits, which returns its lowest quality.
      cardsBudgetBytes  the cap, minus the page with no cards and no image
                        payload, minus that floor: what the cards may spend
                        without costing the picture its existence.
      imageBudgetBytes  the cap minus the page with the cards actually in it:
                        what the picture may spend, after they did.

    The only constant underneath them is PAGE_BYTE_CAP, which is derived above
    from a 1 Mbit/s link and two seconds. THE PROVISIONAL PAGE carries the floor
    encode's own sentence about which quality fitted, and the final one carries
    the final quality's, so the measured skeleton is within a dozen bytes of the
    page that ships; pageBytes on the done line is the number that decides, and
    it is measured on the bytes written.
    """
    dash = load_dashboard()
    cards_mod, cards_why = load_cards()
    sentence = read_sentence(root, now)
    needs = read_needs_you(root, dash)
    cards = read_cards(root, dash, cards_mod, cards_why)
    nxt = read_next(root, sentence)
    budget = read_budget(root)
    # THE FRAME IS PICKED ONCE and encoded twice, so there is one site where
    # the pick happens and the git walk runs once.
    chosen = newest_image(root)

    def assemble(image_look, cards_html, packed):
        looks = (sentence, needs, nxt, image_look, budget)
        colour, why = derive_colour(looks)
        blocks = "\n".join([render_state(sentence, colour, why),
                            render_needs(needs, cards, cards_html, packed),
                            render_next(nxt), render_image(image_look),
                            render_budget(budget)])
        # The sibling first, because it is the page beside this one; the audit
        # level after it. Both are relative names in the same published
        # directory.
        taps = " ".join(['<a href="%s">%s</a>'
                         % (esc(SIBLING[0]), esc(SIBLING[1]))]
                        + ['<a href="%s">%s</a>' % (esc(a), esc(a))
                           for a in AUDIT])
        # The generated-at sentence is read out of the served bytes by
        # tools/publish-glance.py's PAGE_GENERATED regex, so it stays the first
        # thing in this line and unbroken.
        foot = ("Generated by %s at %s. %s Beside this page: %s, every system "
                "as a tile. The audit level, dashboard.html and STATUS.md with "
                "every derivation and denominator, is in the repository and "
                "not yet one tap down."
                % (TOOL, now.strftime("%Y-%m-%d %H:%M UTC"),
                   cards_foot(cards, packed), SIBLING[0]))
        return PAGE % (CSS, blocks, taps, esc(foot)), colour, why, looks

    nothing_packed = {"shown": 0, "notShown": 0, "bytes": 0, "atDrop": None,
                      "budget": 0, "series": []}
    # A BUDGET NOTHING CAN FIT RETURNS THE ENCODER'S LOWEST QUALITY, which is
    # this frame's floor. Measured, not chosen.
    floor_look = read_image(root, 0, chosen=chosen)
    floor = floor_look.get("bytes") or 0
    frame_bytes = len(assemble(floor_look, "", nothing_packed)[0]
                      .encode("utf-8")) - floor
    cards_budget = max(0, PAGE_BYTE_CAP - frame_bytes - floor)
    cards_html, series, used, at_drop = pack_cards(cards.get("cards") or [],
                                                   cards_budget)
    packed = {"shown": sum(1 for r in series if r["shown"]),
              "notShown": sum(1 for r in series if not r["shown"]),
              "bytes": used, "atDrop": at_drop, "budget": cards_budget,
              "series": series}
    skeleton = len(assemble(floor_look, cards_html, packed)[0]
                   .encode("utf-8")) - floor
    image = read_image(root, image_budget if image_budget is not None
                       else max(0, PAGE_BYTE_CAP - skeleton), chosen=chosen)
    page, colour, why, looks = assemble(image, cards_html, packed)
    # EVERY ONE OF THESE IS A WHOLE-RUN NUMBER and belongs on the done line;
    # the per-card bytes go on per-card lines. Sum is cumulative over every
    # pushable card rendered, shown or dropped; Peak is the largest single one;
    # Median is the upper median of the same set.
    costs = sorted(r["bytes"] for r in series)
    keys = ("cardsShown=%d/%d-pushable cardsWaiting=%s cardsNotShown=%d "
            "waitingDashboardThenCardsPy=%s..%s "
            "cardBytesSum=%d cardBytesPeak=%d cardBytesMedian=%s "
            "cardFieldsFound=%d/%d-expected "
            "cardsBudgetBytes=%d imageFloorBytes=%d imageBudgetBytes=%d "
            "ceilingPct=%s ceilingFrom=%s ceilingStandingPct=%s%s"
            % (packed["shown"], cards.get("pushable") or 0,
               cards.get("waiting") if cards.ok else "nothing-measured",
               packed["notShown"],
               needs.get("count") if needs.ok else "nothing-measured",
               cards.get("waiting") if cards.ok else "nothing-measured",
               sum(costs), max(costs or [0]),
               costs[len(costs) // 2] if costs else "nothing-measured",
               sum(r["fields"] for r in series), 3 * len(series),
               cards_budget, floor, max(0, PAGE_BYTE_CAP - skeleton),
               budget.get("ceiling") if budget.ok else "nothing-measured",
               ("%s..%s" % (budget.get("ceiling_from"),
                            str(budget.get("when")).replace(" ", "-")))
               if budget.ok else "nothing-measured",
               budget.get("standing") if budget.ok and
               budget.get("standing") is not None else "nothing-measured",
               "" if at_drop is None else
               " cardFirstDropped=%s..bytes%d..roomAtDrop%d..atIndex%d"
               % (at_drop["id"], at_drop["bytes"], at_drop["roomAtDrop"],
                  at_drop["atIndex"])))
    return page, {"colour": colour, "why": why, "looks": looks, "keys": keys,
                  "cards": cards, "packed": packed,
                  "cardsBudget": cards_budget, "imageFloor": floor}


