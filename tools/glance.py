# ---------------------------------------------------------------------------
# THE FILE CHECKS. The container has no browser, so phone-first is checked on
# the things a FILE can be asked, and then somebody opens it. Each check
# returns (name, ok, printed) and every one of them ships its denominator.
# ---------------------------------------------------------------------------

WIDTH_DECL = re.compile(r"(?:^|[^-\w])((?:min-)?width)\s*:\s*([\d.]+)px", re.I)
REMOTE = re.compile(r"""(?:src|href|action|data|poster)\s*=\s*["']?\s*
                        (https?:|//|ftp:)""", re.I | re.X)
ATTR = re.compile(r"(?:src|href|action|poster)\s*=", re.I)


def check_width(page):
    """Largest fixed or minimum width declared, in CSS px. max-width is not
    counted: it caps a line length and cannot force a horizontal scroll, which
    is the thing 360 exists to prevent."""
    hits = [(m.group(1), float(m.group(2))) for m in WIDTH_DECL.finditer(page)]
    worst = max([v for _, v in hits], default=0.0)
    return ("maxDeclaredWidthPx", worst <= MAX_DECLARED_WIDTH_PX,
            "maxDeclaredWidthPx=%g/%d cap of %d width-or-min-width px "
            "declaration(s)" % (worst, MAX_DECLARED_WIDTH_PX, len(hits)))


def check_external(page):
    hits = REMOTE.findall(page)
    attrs = len(ATTR.findall(page))
    return ("externalRefs", not hits,
            "externalRefs=%d/%d src-or-href attribute(s) examined%s"
            % (len(hits), attrs, "" if not hits else " (" + ",".join(hits) + ")"))


def check_blocks(page):
    n = len(re.findall(r'data-block="\d+"', page))
    return ("blocks", n == 5, "blocks=%d/5 ruled" % n)


def check_weight(page):
    n = len(page.encode("utf-8"))
    return ("pageBytes", n <= PAGE_BYTE_CAP,
            "pageBytes=%d/%d cap (%.0f%% of it)" % (n, PAGE_BYTE_CAP,
                                                    100.0 * n / PAGE_BYTE_CAP))


def check_viewport(page):
    ok = 'name="viewport" content="width=device-width, initial-scale=1"' in page
    return ("viewport", ok, "viewport=%s" % ("device-width" if ok else "MISSING"))


def check_formatting(page):
    """The formatting law, checked on the RENDERED bytes rather than on this
    file: the sentence is quoted from a source this tool does not own, so an
    em-dash can arrive from production/outbox without anyone editing code
    here. The page never silently rewrites a judgement, so it fails loudly
    instead and names what to fix."""
    ems = page.count("—") + page.count("–")
    ital = len(re.findall(r"<em\b|<i\b|font-style\s*:\s*italic", page, re.I))
    return ("formatting", ems == 0 and ital == 0,
            "emDashes=%d italics=%d/%d chars examined" % (ems, ital, len(page)))


def check_secrets(page):
    """The repo is public and Jafar ruled that knowingly, so this is not a
    secrecy check. It is the one line that stops a future source file from
    dragging a token onto a world-readable page."""
    bad = [w for w in ("config.local", "TELEGRAM_TOKEN", "BEGIN PRIVATE KEY")
           if w in page]
    tokenish = re.findall(r"\b\d{8,}:[A-Za-z0-9_-]{30,}\b", page)
    return ("secrets", not bad and not tokenish,
            "secretMarkers=%d/3 examined tokenShaped=%d"
            % (len(bad), len(tokenish)))


def check_map_link(page):
    """THE FORWARD LINK, COUNTED RATHER THAN ASSUMED. Exactly one href to the
    sibling, and it is a link and not an embed: a second copy of the map inside
    this page would be the sixth block the specification forbids. The count is
    printed with its denominator so a page that grew a second one, or lost the
    only one, is not read as fine."""
    n = len(re.findall(r'href="%s"' % re.escape(SIBLING[0]), page))
    return ("mapLink", n == 1, "mapLink=%d/1 href(s)-to-%s label=%s"
            % (n, SIBLING[0], SIBLING[1].replace(" ", "-")))


CHECKS = (check_blocks, check_viewport, check_width, check_external,
          check_weight, check_formatting, check_secrets, check_map_link)


def run_checks(page):
    return [f(page) for f in CHECKS]


