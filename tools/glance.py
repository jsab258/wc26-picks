def plant(tmp, sentence=True, queue=True, budget=True, image=True,
          budget_text=None, queue_text=None):
    """A fixture tree with any of the four source files withheld, so the
    missing-source half can be proven one source at a time.

    budget_text and queue_text swap ONE file's contents for another rung of the
    same ladder, leaving every other input identical.
    """
    root = Path(tmp)
    if sentence:
        d = root / SENTENCE_DIR
        d.mkdir(parents=True, exist_ok=True)
        (d / "2026-09-05-fixture.unprompted.md").write_text(FIXTURE_SENTENCE)
    if queue:
        (root / DECISIONS).parent.mkdir(parents=True, exist_ok=True)
        (root / DECISIONS).write_text(queue_text or FIXTURE_QUEUE)
    if budget:
        (root / BUDGET).parent.mkdir(parents=True, exist_ok=True)
        (root / BUDGET).write_text(budget_text or FIXTURE_BUDGET)
    if image:
        d = root / "game-design" / "sim-shots"
        d.mkdir(parents=True, exist_ok=True)
        from PIL import Image
        Image.new("RGB", (1600, 900), (40, 60, 80)).save(d / "fixture.jpg",
                                                         quality=85)
    return root


