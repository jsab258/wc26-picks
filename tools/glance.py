# animation thumbnails, and it embedded cleanly at 84 per cent of the weight
# cap with every check green. On a 390 point screen it is a grey smear. A frame
# with no recognised prefix is now last, and it is offered only when the commit
# holds nothing else.
FRAME_ORDER = ("review_day1_noon", "review_day1_night")
FRAME_PREFIXES = ("review_", "hunt_", "district_")


def choose_frame(paths):
    """One frame out of the commit's set, by report-frame.py's order. Returns
    the pick and the sentence naming which rule chose it, because a tie-break
    nobody can read is a tie-break nobody can correct."""
    for want in FRAME_ORDER:
        for p in paths:
            if p.stem == want:
                return p, ("%s was chosen by tools/report-frame.py's default "
                           "order" % p.name)
    stills = sorted(p for p in paths if p.name.startswith(FRAME_PREFIXES))
    if stills:
        return stills[0], ("%s is the first of %d frame(s) carrying a "
                           "report-frame.py prefix" % (stills[0].name, len(stills)))
    first = sorted(paths)[0]
    return first, ("%s was taken by path order because no frame in that commit "
                   "carries a %s prefix" % (first.name, "/".join(FRAME_PREFIXES)))


def newest_image(root):
    """The latest image, by COMMIT time where git knows and by file time where
    it does not, and the page says which rule chose the file.

    Commit time is the right key in a checkout: every file's mtime is the time
    the clone was made, so an mtime sort would pick whatever the filesystem
    happened to write last. A tree with no git history (a planted fixture, or a
    frame rendered and not yet committed) falls back to mtime, named as such.
    """
    dirs = [d for d in IMAGE_DIRS if (root / d).is_dir()]
    if not dirs:
        return None, "none of %s exists" % ", ".join(IMAGE_DIRS), 0
    on_disk = [p for d in dirs for p in sorted((root / d).rglob("*"))
               if p.suffix.lower() in IMAGE_SUFFIXES]
    if not on_disk:
        return None, "no %s file under %s" % ("/".join(IMAGE_SUFFIXES),
                                              " or ".join(dirs)), 0
    log = git(root, "log", "--format=commit %H", "--name-only", "-60", "--", *dirs)
    commits, sha, seen = [], None, 0
    for line in log.splitlines():
        if line.startswith("commit "):
            sha = line.split()[1]
            commits.append((sha, []))
            continue
        if commits and line.strip() and Path(line).suffix.lower() in IMAGE_SUFFIXES:
            p = root / line.strip()
            seen += 1
            if p.exists():
                commits[-1][1].append(p)
    for sha, paths in commits:
        if not paths:
            continue
        ran, stamp = measuring_run(root, sha)
        if not ran:
            continue
        pick, rule = choose_frame(paths)
        return pick, ("newest committed frame under %s whose run verdict "
                      "game-design/sim-shots/runs/%s.txt says the sim measured "
                      "something; that commit carries %d frame(s) and %s; of "
                      "%d committed image path(s) walked over %d commit(s)"
                      % (" or ".join(dirs), stamp[:7], len(paths), rule, seen,
                         len(commits))), len(on_disk)
    if seen:
        return None, ("no commit among the %d touching %s came from a run "
                      "that measured anything, so no frame is offered: a "
                      "still from a build that rendered nothing is not the "
                      "latest picture of anything"
                      % (len(commits), " or ".join(dirs))), len(on_disk)
    newest = max(on_disk, key=lambda p: p.stat().st_mtime)
    return newest, ("newest file by modification time under %s, because git "
                    "has no history for those paths in this tree; of %d image "
                    "file(s) found" % (" or ".join(dirs), len(on_disk))), len(on_disk)


def encode_image(path, budget):
    """Embed the frame as a data URI, at the largest quality that fits.

    THE QUALITY IS NOT A GUESS: the loop takes the first encode whose base64
    length fits the weight left over after the page shell, so the number that
    governs is the measured byte budget above and not a taste setting. The
    encoded size is printed every run.
    """
    try:
        from PIL import Image
    except ImportError:
        raw = path.read_bytes()
        b64 = base64.b64encode(raw).decode("ascii")
        return (b64, "image/jpeg", len(b64), "Pillow is not installed, so the "
                "frame is embedded unresized", None)
    with Image.open(path) as im:
        im = im.convert("RGB")
        w, h = im.size
        if w > IMAGE_WIDTH_PX:
            im = im.resize((IMAGE_WIDTH_PX, max(1, round(h * IMAGE_WIDTH_PX / w))),
                           Image.LANCZOS)
        out, used = None, None
        for q in IMAGE_QUALITIES:
            buf = io.BytesIO()
            im.save(buf, "JPEG", quality=q, optimize=True)
            b64 = base64.b64encode(buf.getvalue()).decode("ascii")
            out, used = b64, q
            if len(b64) <= budget:
                break
    return (out, "image/jpeg", len(out),
            "%d by %d source, resized to %d wide for a 2x phone screen and "
            "encoded at JPEG quality %d, the first that fits the %d byte "
            "budget left by the page shell" % (w, h, min(w, IMAGE_WIDTH_PX),
                                               used, budget), used)


def read_image(root, budget, chosen=None):
    """BLOCK 4: the latest image, embedded. If there is none, the block says
    the words "nothing measured" rather than showing a broken image, which on a
    phone is indistinguishable from a page that failed to load.

    `chosen` is an already-taken (path, why, denom) from newest_image, handed in
    by build so that the frame is PICKED ONCE and encoded twice: once at a
    budget nothing fits, to measure the floor the cards must leave it, and once
    at what the cards left. Calling newest_image again instead would run the
    git walk twice and, worse, be a second site where the pick could drift.
    """
    path, why, denom = chosen if chosen is not None else newest_image(root)
    if path is None:
        return Look.missing(" or ".join(IMAGE_DIRS), why)
    rel = path.relative_to(root).as_posix()
    try:
        b64, mime, n, how, _q = encode_image(path, budget)
    except OSError as e:
        return Look.missing(rel, "%s could not be read or decoded: %s" % (rel, e))
    return Look.measured(rel, "%s; %s" % (why, how), b64=b64, mime=mime, bytes=n,
                         examined=denom)


CEILING = re.compile(r"Ceiling for LEDGER:\s*(\d+)\s*%")
# THE CEILING JAFAR RULED IN THE SAME MESSAGE AS THE READING, read off the
# SELECTED ROW'S OWN WORDS. Until 2026-09-09 this page took the ceiling from
# production/budget.md's standing "Ceiling for LEDGER: 80%" line over the whole
# file, and drew his bar against 80 while the row it was reading said, in its
# own words, "THE CEILING FOR THIS SESSION IS 75 ON THE GOVERNING METER, set by
# him in the same message, not the standing 80". A bar drawn against a ceiling
# he retired is a false reading with a number on it.
#
# TIGHT ON PURPOSE, and the selftest's rejecting fixtures are what the
# tightness is for. The phrase has to carry the number AND the words "on the
# governing meter" after it, because the same column also says "4x over pace
# against the 80% ceiling", "3 POINTS TO THE CEILING", "47 points to the 80
# ceiling" and "the 80 ceiling is CROSSED on the governing meter", and any
# pattern loose enough to read an integer near the word ceiling out of those
# would invent a ruling out of prose. Rows are one line each in the table, so
# this never spans two readings.
ROW_CEILING = re.compile(
    r"\bthe ceiling\b(?:\s+\w+){0,3}?\s+is\s+(\d{1,3})\s*%?\s+"
    r"on the governing meter\b", re.I)
PERCENT = re.compile(r"(\d+)\s*%")
HOURS_TO_RESET = re.compile(r"([\d.]+)\s*hours to the")


def meter(cell):
    """One meter cell: a percentage, or None for not read. A cell that says
    `not read` is a true statement about what was measured and never a zero,
    and it is never filled in from the other meter: on 2026-09-01 Fable led the
    total by seven and on 2026-09-04 the total led Fable by one, so there is no
    rule of thumb to infer one from the other."""
    t = cell.strip().lower()
    if not t or "not read" in t or "no percentage" in t:
        return None
    m = PERCENT.search(t)
    return int(m.group(1)) if m else None


def read_budget(root):
    """BLOCK 5: both meters against the ceiling, the governing one marked, and
    hours to reset.

    THE NEWEST ROW IS NOT ALWAYS A READING. production/budget.md carries rows
    for limit EVENTS, which it says in its own words must never be counted as
    readings because they carry no percentage on either meter. So this takes
    the newest row that carries a percentage on at least one meter, and prints
    how many newer rows were skipped for carrying none.

    THE DASHBOARD READS THIS FILE TOO, AND DIFFERENTLY, so the two are named
    to each other rather than left to drift apart unnoticed. read_budget in
    tools/dashboard/build-dashboard.py takes the LAST table row and the TOTAL
    column alone, which is why STATUS.md today prints "weekly Claude usage:
    not read used at 2026-09-05": it is quoting the limit-event row's own
    words as a value, and it never mentions the Fable meter that the
    2026-09-03 two-meter ruling made governing. That is a queue item against
    the dashboard and not something this page quietly patches, but a reader
    comparing the two surfaces has to be told they disagree on purpose.
    """
    path = root / BUDGET
    text = read_text(path)
    if text is None:
        return Look.missing(BUDGET, "%s does not exist" % BUDGET)
    rows = []
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5 or cells[0].lower() == "when" or set(cells[0]) <= set("-: "):
            continue
        rows.append(cells)
    reading, skipped = None, 0
    for cells in reversed(rows):
        if meter(cells[2]) is not None or meter(cells[3]) is not None:
            reading = cells
            break
        skipped += 1
    if reading is None:
        return Look.missing(BUDGET, "none of the %d table row(s) in %s carries "
                            "a percentage on either meter" % (len(rows), BUDGET))
    # THE NOTE IS EVERY CELL FROM THE FIFTH ON, joined: a note that happens to
    # carry a pipe would otherwise have its tail parsed as a sixth column and
    # a ceiling ruled in that tail would be invisible.
    note_text = " ".join(reading[4:])
    ruled = ROW_CEILING.search(note_text)
    standing = CEILING.search(text)
    if ruled is None and standing is None:
        return Look.missing(BUDGET, "the %s row rules no ceiling on the "
                            "governing meter and %s carries no 'Ceiling for "
                            "LEDGER: N%%' line either, so there is no ceiling "
                            "to draw a bar against" % (reading[0], BUDGET))
    standing_pct = int(standing.group(1)) if standing else None
    if ruled is not None:
        ceiling, ceiling_from = int(ruled.group(1)), "the-row"
        how = ("the ceiling is THE SELECTED ROW'S OWN RULING, quoting it, '%s', "
               "and not the file's standing %s line, because a ceiling is set "
               "in the same message as the reading"
               % (ruled.group(0),
                  "%d%%" % standing_pct if standing_pct is not None
                  else "(which is absent)"))
    else:
        ceiling, ceiling_from = standing_pct, "the-standing-line"
        how = ("the ceiling is the file's standing '%d%%' line, used because "
               "the %s row rules none of its own on the governing meter"
               % (ceiling, reading[0]))
    total, fable = meter(reading[2]), meter(reading[3])
    govern = "total" if (fable is None or (total is not None and total >= fable)) \
        else "fable"
    hrs = HOURS_TO_RESET.search(note_text)
    return Look.measured(
        BUDGET, "the newest row in %s carrying a percentage on either meter, "
                "of %d row(s) read, %d newer row(s) skipped for carrying none "
                "on either; %s; hours to reset is printed only when the row's "
                "note states it"
                % (BUDGET, len(rows), skipped, how),
        when=reading[0], total=total, fable=fable, ceiling=ceiling,
        ceiling_from=ceiling_from, standing=standing_pct,
        ruled_pct=int(ruled.group(1)) if ruled else None,
        govern=govern, hours=float(hrs.group(1)) if hrs else None,
        rows=len(rows), skipped=skipped)


def ceiling_source(budget):
    """Where the ceiling on the bar came from, in words, for the page and for
    the done line.

    IT IS PRINTED EVERY RUN AND NOT ONLY WHEN IT IS THE INTERESTING ONE. A
    number whose provenance is invisible is the next silent fault of exactly
    this kind: the 80 this page drew on 2026-09-09 was read off a standing line
    nobody had looked at since it was written, and nothing on the page said so.
    """
    if budget.get("ceiling_from") == "the-row":
        return ("ruled by the %s row itself, not the standing %s line in %s"
                % (budget.get("when"),
                   "%d%%" % budget.get("standing")
                   if budget.get("standing") is not None else "(absent)",
                   BUDGET))
    return ("from the standing line in %s, which the %s row does not override"
            % (BUDGET, budget.get("when")))


# THE COLOUR, DERIVED FROM NAMED INPUTS AND NOTHING ELSE. No threshold here was
# picked by this tool: GREY is queue 096's staleness ruling plus the standing
# rule that a missing reading is never a green one; RED is budget.md's own rule
# that LEDGER STOPS at the ceiling; AMBER is interrupt-classes.md, where
# BLOCKING means the studio has stopped or is about to do something
# irreversible, and where a card with no CLASS is reported as unclassified by
# every reader rather than routed by default.
def derive_colour(looks):
    sentence, needs, nxt, image, budget = looks
    blind = [name for name, look in
             (("state", sentence), ("needs-you", needs), ("next", nxt),
              ("image", image), ("budget", budget)) if not look.ok]
    if blind:
        return "GREY", ("%d of 5 readings could not be taken (%s), and a "
                        "console that reports green while blind is the fault "
                        "this page exists to end"
                        % (len(blind), ", ".join(blind)))
