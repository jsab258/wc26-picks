class Inventory:
    """What the check said, and nothing this file decided.

    `code` is the check's own exit code (0 accepted, 1 refused, 2 nothing
    measured, 3 could not run), `entries` is the validated JSON it emitted on
    stdout and is None for every non-zero code, and `report` is its report
    verbatim, which is what names the offending entry on a refusal.
    """

    def __init__(self, code, entries, report, source):
        self.code = code
        self.entries = entries
        self.report = report
        self.source = source

    @property
    def ok(self):
        return self.code == 0 and self.entries is not None

    WORD = {0: "accepted", 1: "REFUSED", 2: NOTHING, 3: "the check could not run"}

    @property
    def word(self):
        return self.WORD.get(self.code, "unknown exit %d" % self.code)


def read_inventory(check, path, names_path=None):
    """Run the check with --emit-json and keep both halves of what it says.

    The report goes to stderr and the validated entries to stdout precisely so
    that a refused inventory cannot be rendered as a page, so both streams are
    captured here and the exit code is obeyed rather than inspected for a
    usable remnant.
    """
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = check.run(str(path), names_path, emit=True)
    report = err.getvalue().strip()
    entries = None
    if code == 0:
        body = out.getvalue().strip()
        try:
            entries = json.loads(body) if body else None
        except ValueError as exc:
            code, report = 3, ("%s exited 0 but its emitted JSON did not parse "
                               "(%s)\n%s" % (CHECK_TOOL, exc, report))
    return Inventory(code, entries, report, check.rel(str(path)))


