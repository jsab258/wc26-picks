# THE LAYOUT MODEL. Python decides the spans and counts the rows, and the CSS
# below is generated from the same constants, so there is one set of numbers
# and not two that can drift.
# ---------------------------------------------------------------------------

def column_px():
    """One grid column at the stated phone width, in CSS px."""
    content = PHONE_WIDTH_PX - 2 * BODY_PAD_PX
    return (content - (COLUMNS - 1) * GAP_PX) / float(COLUMNS)


def chars_per_line(span):
    """How many characters fit across a tile of this span, under the stated
    average advance. Named as an estimate everywhere it is used."""
    inner = span * column_px() + (span - 1) * GAP_PX - 2 * TILE_PAD_PX
    return int(inner / (NAME_FONT_PX * AVG_ADVANCE_EM))


def wrap(name, cpl):
    """Greedy word wrapping, the way a browser does it. A single word longer
    than the line is left on its own line and overflows, which is what a
    browser does too and what the nameLines check exists to catch."""
    lines, cur = [], ""
    for word in name.split():
        joined = (cur + " " + word).strip()
        if len(joined) <= cpl or not cur:
            cur = joined
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines or [""]


def fit(name):
    """(span, lines) for one name: one column if it fits, otherwise two."""
    for span in range(1, MAX_SPAN + 1):
        cpl = chars_per_line(span)
        lines = wrap(name, cpl)
        if len(lines) <= LINES_PER_TILE and max(len(l) for l in lines) <= cpl:
            return span, lines
    return MAX_SPAN, wrap(name, chars_per_line(MAX_SPAN))


def layout(check, entries):
    """Group into the five areas in the check's own order and count the rows.

    The row count MIRRORS CSS GRID AUTO-PLACEMENT as the browser performs it:
    row flow, sparse, so an item that does not fit in the columns left starts a
    new row and leaves the hole behind. Modelling it any other way would make
    the height arithmetic below a different page's arithmetic.
    """
    groups, rows_total = [], 0
    placed = 0
    for area in check.AREAS:
        members = [e for e in entries if e.get("area") == area]
        col, rows = 0, 1 if members else 0
        tiles = []
        for e in members:
            span, lines = fit(str(e.get("name", "")))
            if col + span > COLUMNS:
                rows += 1
                col = 0
            col += span
            placed += 1
            tiles.append({"entry": e, "span": span, "lines": lines})
        groups.append({"area": area, "tiles": tiles, "rows": rows})
        rows_total += rows
    return {"groups": groups, "rows": rows_total, "placed": placed}


def layout_height(model):
    """The page's height at PHONE_WIDTH_PX, in CSS px, from the same constants
    the stylesheet is generated from. A sum, not a sample."""
    h = BODY_PAD_PX + TITLE_PX + LEGEND_GAP_ABOVE_PX + LEGEND_PX \
        + LEGEND_GAP_BELOW_PX
    for g in model["groups"]:
        if not g["tiles"]:
            continue
        h += AREA_HEAD_PX + AREA_HEAD_GAP_PX
        h += g["rows"] * TILE_PX + (g["rows"] - 1) * GAP_PX + AREA_MARGIN_PX
    return h + FOOT_GAP_PX + FOOT_PX + BODY_PAD_BOTTOM_PX


def worst_name(model):
    """The name closest to overflowing its tile, with its predicted lines. This
    is a peak and it is named as one: it answers "did any name ever need a
    fourth line", which is the only question the tile geometry cares about."""
    worst = None
    for g in model["groups"]:
        for t in g["tiles"]:
            n = len(t["lines"])
            if worst is None or n > worst[1]:
                worst = (str(t["entry"].get("name")), n, t["span"])
    return worst


# ---------------------------------------------------------------------------
# THE BLOCKER, RESOLVED TO A DECISION RECORD OR A QUEUE FILE. The data says
# `D1` or `queue-046` or `none`; the sheet says which file that is and what its
# heading calls it. Nothing is inferred: a blocker whose file cannot be found
# is printed as not found, with the folder that was searched.
# ---------------------------------------------------------------------------

D_NUMBER = re.compile(r"^D\d+$")
HEADING = re.compile(r"^#\s+(.*)$", re.M)


def first_heading(path):
    try:
        m = HEADING.search(path.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return None
    return m.group(1).strip() if m else None


def resolve_blocker(root, blocker):
    """(word, decision_line) for one blocker value, both from disk."""
    b = str(blocker) if blocker is not None else ""
    if not b or b == "none":
        return "none", "the inventory says none, so no decision is named"
    if D_NUMBER.match(b):
        d = root / DECISION_DIR
        hits = sorted(p for p in d.glob(b + "-*.md")) if d.is_dir() else []
        if not hits:
            return b, "no record named %s-*.md under %s" % (b, DECISION_DIR)
        title = first_heading(hits[0]) or hits[0].name
        return b, "%s (%s)" % (title, hits[0].relative_to(root).as_posix())
    if b.startswith("queue-"):
        num = b[len("queue-"):]
        for folder in QUEUE_DIRS:
            d = root / folder
            if d.is_dir():
                hits = sorted(p for p in d.glob(num + "-*.md"))
                if hits:
                    return b, "%s/%s" % (folder, hits[0].name)
        return b, "no queue file named %s-*.md under %s" % (num,
                                                            " or ".join(QUEUE_DIRS))
    return b, ("not a decision record (D<n>) or a queue item (queue-<n>), so "
               "no file was looked for")


