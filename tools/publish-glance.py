#!/usr/bin/env python3
"""PUBLISH THE GLANCE to a URL Jafar can open on his phone, and PROVE the page
that is served is the page we built.

    python3 tools/publish-glance.py --build --out-dir _site --commit <sha>
    python3 tools/publish-glance.py --check <url> --expect-commit <sha>
    python3 tools/publish-glance.py --selftest

WHY THIS EXISTS AND WHAT IT IS NOT. `tools/glance.py` (queue 096, another
owner) generates the page, and `tools/map.py` (queue 099) generates the second
page published beside it. This file does not generate anything and does not
read either page's sources. It does three things a generator must not be asked
to do: it STAMPS the built bytes so a served body can be identified, it SCANS
the bytes it is about to publish, and it REQUESTS the published URL and reports
what came back. Both generators are consumed here by subprocess, unmodified.
The site is `SITE_FILES` below, which is the one place its file count is
written down.

THE ONE DISTINCTION THIS FILE IS FOR (queue 097 acceptance, verbatim): "a
request that does not complete (proxy refusal, timeout) prints the words
'nothing measured' with the error, and is never reported as 404". A 404 means
the site is not there. A refused request means WE DID NOT FIND OUT. Conflating
them reports a proxy's opinion as GitHub's. `fetch()` below returns a `measured`
flag and every verdict path branches on it before it looks at a status code.

A THIRD CASE THE STATUS CODE CANNOT SEE. This repository's `main` root carries
an unrelated `index.html` from the repository's prior life ("WC26 Picks"). If
Pages serves that, the request returns 200 and text/html and is NOT our page.
So 200 is never sufficient: the body must carry OUR stamp, and the stamp must
name the commit we expect. `pageResult=NOT-PUBLISHED reason=no-stamp-in-body`
is that case, and it is why the check does not stop at the status line.

WHY THE STAMP IS INJECTED HERE RATHER THAN GENERATED, corrected after the
first claim was wrong. The generated page DOES carry a dated sentence: the
footer reads "Generated by tools/glance.py at <date> <time> UTC". An earlier
probe here reported no clock in the page; that probe required 70 characters of
context on both sides of a date on one line, and the footer has about 48 before
it, so the instrument under-reported and the conclusion drawn from it was
false. The footer date is read and PRINTED as `pageGeneratedAt`, which is the
acceptance clause's "dated sentence from the newest generated page".

The stamp still earns its line, for the thing the footer cannot do: the footer
carries no commit, so it cannot answer "is this the page THIS commit built".
Staleness is decided on commit equality, and only the stamp carries a commit.
Rather than edit another builder's file, the publish step adds exactly one HTML
comment after the doctype. Nothing visible changes; the published bytes differ
from the generator's output by that comment and nothing else, measured by diff
2026-09-05 and asserted by `--selftest`.

STALENESS IS DECIDED BY COMMIT EQUALITY, NOT BY A TIME BOUND. An exact
comparison needs no threshold and CLAUDE.md rule 2 forbids inventing one. Age
in minutes is PRINTED on every run (the acceptance asks for it, and a printed
series is what a future bound would be set from); it only gates when
`--max-age-min` is passed explicitly.
"""
